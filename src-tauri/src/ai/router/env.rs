//! Renders the sidecar's `.env`. Pure so tests can assert every key and the absence of secrets. Lynkr reads only
//! `<cwd>/.env` (dotenv); `PORT` and `MODEL_PRICE_OVERRIDES` need a restart, `TIER_*` hot-reload.
use super::{Assignment, Tier};
use crate::core::settings::ModelConfig;
use std::path::Path;

pub struct EnvConfig<'a> {
    pub port: u16,
    pub bridge_messages_url: String,
    pub bridge_token: String,
    pub lynkr_api_key: String,
    pub assignment: &'a Assignment,
    pub models: &'a [ModelConfig],
    pub sticky_sessions: bool,
    pub tpm_limit: Option<u32>,
    pub prefix: &'a Path,
    /// (endpoint base e.g. http://localhost:11434, model) when an Ollama provider is configured for embeddings.
    pub ollama_embeddings: Option<(String, String)>,
}

fn q(v: &str) -> String { format!("'{}'", v.replace('\'', "'\\''")) }

/// `MODEL_PRICE_OVERRIDES` JSON: prices + context for **every enabled model** (not just the four assigned ones) so that
/// swapping a tier to another configured model only changes `TIER_*` lines — which Lynkr hot-reloads — instead of
/// forcing a restart (Lynkr parses this variable once at startup). `lynkr-auto` gets the smallest window so Lynkr's
/// token budgets never exceed what any routed model accepts.
pub fn price_overrides_json(assignment: &Assignment, models: &[ModelConfig]) -> String {
    let mut map = serde_json::Map::new();
    let mut min_ctx: Option<u32> = None;
    let assigned: std::collections::HashSet<&str> = Tier::ALL.iter().filter_map(|t| assignment.get(*t)).map(|s| s.model_id.as_str()).collect();
    for m in models.iter().filter(|m| m.enabled || assigned.contains(m.id.as_str())) {
        if m.model.eq_ignore_ascii_case("lynkr-auto") { continue; }
        min_ctx = Some(min_ctx.map_or(m.context_window, |c| c.min(m.context_window)));
        map.insert(m.id.clone(), serde_json::json!({ "input": m.input_price_per_m.unwrap_or(0.0), "output": m.output_price_per_m.unwrap_or(0.0), "context": m.context_window }));
    }
    if let Some(c) = min_ctx { map.insert("lynkr-auto".into(), serde_json::json!({ "input": 0.0, "output": 0.0, "context": c })); }
    serde_json::Value::Object(map).to_string()
}

pub fn render_env(c: &EnvConfig) -> String {
    let prefix = c.prefix.to_string_lossy();
    let mut out = String::new();
    out.push_str("# Generated by Caret — do not edit; Caret rewrites this file when your models or Auto routing settings change.\n");
    out.push_str(&format!("PORT={}\n", c.port));
    out.push_str("MODEL_PROVIDER=azure-anthropic\n");
    out.push_str(&format!("AZURE_ANTHROPIC_ENDPOINT={}\n", q(&c.bridge_messages_url)));
    out.push_str(&format!("AZURE_ANTHROPIC_API_KEY={}\n", q(&c.bridge_token)));
    out.push_str("AZURE_ANTHROPIC_VERSION=2023-06-01\n");
    for t in Tier::ALL { if let Some(s) = c.assignment.get(t) { out.push_str(&format!("{}=azure-anthropic:{}\n", t.env_key(), s.model_id)); } }
    if let Some(s) = c.assignment.get(Tier::Complex) { out.push_str(&format!("MODEL_DEFAULT={}\n", s.model_id)); }
    out.push_str(&format!("MODEL_PRICE_OVERRIDES={}\n", q(&price_overrides_json(c.assignment, c.models))));
    out.push_str("FALLBACK_ENABLED=false\nLYNKR_VISIBLE_ROUTING=false\nLYNKR_NATIVE_PASSTHROUGH=true\nLYNKR_STREAM_TRANSFORM=true\n");
    out.push_str(&format!("LYNKR_STICKY_SESSIONS={}\n", c.sticky_sessions));
    out.push_str("MEMORY_ENABLED=false\nTOOL_RESULT_COMPRESSION_ENABLED=false\nPROMPT_CACHE_ENABLED=false\nTOKEN_BUDGET_ENFORCEMENT=false\n");
    out.push_str("RATE_LIMIT_ENABLED=false\nSECURITY_RATE_LIMIT_ENABLED=false\nCAVEMAN_ENABLED=false\nTOON_ENABLED=false\nCLUSTER_ENABLED=false\nHEADROOM_ENABLED=false\n");
    out.push_str("HOT_RELOAD_ENABLED=true\nLOG_LEVEL=info\nLOG_FILE_ENABLED=true\n");
    out.push_str(&format!("LOG_FILE_PATH={}\n", q(&format!("{prefix}/logs/lynkr.log"))));
    out.push_str(&format!("SESSION_DB_PATH={}\n", q(&format!("{prefix}/data/sessions.db"))));
    out.push_str(&format!("LYNKR_KNN_DIR={}\n", q(&format!("{prefix}/data/knn"))));
    out.push_str(&format!("WORKSPACE_ROOT={}\n", q(&prefix)));
    if let Some((base, model)) = &c.ollama_embeddings {
        out.push_str(&format!("OLLAMA_EMBEDDINGS_ENDPOINT={}\n", q(&format!("{}/api/embeddings", base.trim_end_matches('/').trim_end_matches("/v1")))));
        out.push_str(&format!("OLLAMA_EMBEDDINGS_MODEL={}\n", q(model)));
    }
    if let Some(t) = c.tpm_limit { out.push_str(&format!("LYNKR_TPM_LIMIT={t}\n")); }
    out.push_str("LYNKR_BIND_HOST=127.0.0.1\n");
    out.push_str(&format!("LYNKR_API_KEY={}\n", q(&c.lynkr_api_key)));
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use super::super::TierSlot;
    fn model(id: &str, ctx: u32, inp: f64) -> ModelConfig { ModelConfig { id: id.into(), model: id.into(), display_name: id.into(), context_window: ctx, max_output: 8192, input_price_per_m: Some(inp), output_price_per_m: Some(inp * 5.0), enabled: true, ..Default::default() } }
    fn assignment() -> Assignment {
        let mut a = Assignment::default();
        for (t, id) in [(Tier::Simple, "haiku"), (Tier::Medium, "sonnet"), (Tier::Complex, "sonnet"), (Tier::Reasoning, "opus")] { a.slots.insert(t.key().into(), TierSlot { model_id: id.into(), source: "auto".into(), reason: None }); }
        a
    }
    fn cfg<'a>(a: &'a Assignment, models: &'a [ModelConfig]) -> EnvConfig<'a> {
        EnvConfig { port: 48123, bridge_messages_url: "http://127.0.0.1:48001/v1/messages".into(), bridge_token: "tok-bridge-123".into(), lynkr_api_key: "key-lynkr-456".into(), assignment: a, models, sticky_sessions: true, tpm_limit: Some(50_000), prefix: Path::new("/Users/me/.caret/lynkr"), ollama_embeddings: Some(("http://localhost:11434/v1".into(), "nomic-embed-text".into())) }
    }

    #[test]
    fn renders_every_required_key() {
        let a = assignment(); let models = vec![model("haiku", 200_000, 1.0), model("sonnet", 1_000_000, 3.0), model("opus", 1_000_000, 15.0)];
        let env = render_env(&cfg(&a, &models));
        for k in ["PORT=48123", "MODEL_PROVIDER=azure-anthropic", "AZURE_ANTHROPIC_ENDPOINT='http://127.0.0.1:48001/v1/messages'", "AZURE_ANTHROPIC_API_KEY='tok-bridge-123'", "TIER_SIMPLE=azure-anthropic:haiku", "TIER_MEDIUM=azure-anthropic:sonnet", "TIER_COMPLEX=azure-anthropic:sonnet", "TIER_REASONING=azure-anthropic:opus", "MODEL_DEFAULT=sonnet", "FALLBACK_ENABLED=false", "LYNKR_VISIBLE_ROUTING=false", "LYNKR_STICKY_SESSIONS=true", "MEMORY_ENABLED=false", "TOKEN_BUDGET_ENFORCEMENT=false", "LYNKR_TPM_LIMIT=50000", "OLLAMA_EMBEDDINGS_ENDPOINT='http://localhost:11434/api/embeddings'", "OLLAMA_EMBEDDINGS_MODEL='nomic-embed-text'", "LYNKR_BIND_HOST=127.0.0.1", "LYNKR_API_KEY='key-lynkr-456'", "SESSION_DB_PATH='/Users/me/.caret/lynkr/data/sessions.db'"] {
            assert!(env.lines().any(|l| l == k), "missing line {k}\n{env}");
        }
    }

    #[test]
    fn price_overrides_are_valid_json_with_min_context_for_auto() {
        let a = assignment(); let models = vec![model("haiku", 200_000, 1.0), model("sonnet", 1_000_000, 3.0), model("opus", 1_000_000, 15.0)];
        let v: serde_json::Value = serde_json::from_str(&price_overrides_json(&a, &models)).unwrap();
        assert_eq!(v["haiku"]["context"], 200_000); assert_eq!(v["opus"]["input"], 15.0); assert_eq!(v["lynkr-auto"]["context"], 200_000);
        let env = render_env(&cfg(&a, &models));
        let line = env.lines().find(|l| l.starts_with("MODEL_PRICE_OVERRIDES=")).unwrap();
        assert!(line.ends_with('\'') && line.contains("'{"), "JSON must be single-quoted for dotenv: {line}");
    }

    #[test]
    fn omits_optional_sections_and_never_leaks_provider_keys() {
        let a = assignment(); let models = vec![model("haiku", 200_000, 1.0)];
        let mut c = cfg(&a, &models); c.tpm_limit = None; c.ollama_embeddings = None;
        let env = render_env(&c);
        assert!(!env.contains("LYNKR_TPM_LIMIT") && !env.contains("OLLAMA_EMBEDDINGS"));
        assert!(!env.contains("sk-ant-") && !env.lines().any(|l| l.starts_with("ANTHROPIC_API_KEY=") || l.starts_with("OPENAI_API_KEY=") || l.starts_with("OPENROUTER_API_KEY=")));
    }
}
